r"""
generate_trace.py — Generate real expansion trace for Scenario 2 (AC-2 under A*).

Runs the crossing routes scenario with search tracing enabled, saving:
  1. outputs/trace_scenario2_AC-2_astar.csv
  2. reports/trace_table.tex (LaTeX table fragment to be \input in report.tex)
"""

import os
import csv
from src.scenarios import scenario_crossing
from src.simulation import Simulation


def generate_trace():
    base_dir = os.path.dirname(os.path.abspath(__file__))
    outputs_dir = os.path.join(base_dir, "outputs")
    reports_dir = os.path.join(base_dir, "reports")
    os.makedirs(outputs_dir, exist_ok=True)
    os.makedirs(reports_dir, exist_ok=True)

    grid, aircraft = scenario_crossing()
    sim = Simulation(grid, aircraft, algorithm="A*", record_trace=True)
    success = sim.plan()
    if not success:
        raise RuntimeError("Scenario 2 planning failed unexpectedly.")

    ac2 = next(a for a in sim.aircraft if a.aircraft_id == "AC-2")
    res = ac2.search_result
    if res is None or not res.expansion_trace:
        raise RuntimeError("No expansion trace found for AC-2.")

    # Enforce invariant
    assert len(res.expansion_trace) == res.nodes_expanded, (
        f"Invariant failed: len(trace)={len(res.expansion_trace)} != nodes_expanded={res.nodes_expanded}"
    )

    # 1. Write CSV
    csv_path = os.path.join(outputs_dir, "trace_scenario2_AC-2_astar.csv")
    with open(csv_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["Step", "State", "x", "y", "t", "g", "h", "f", "Blocked Successors"])
        for r in res.expansion_trace:
            writer.writerow([
                r.step,
                f"({r.state[0]}, {r.state[1]}, {r.state[2]})",
                r.state[0],
                r.state[1],
                r.state[2],
                f"{r.g:.1f}",
                f"{r.h:.1f}",
                f"{r.f:.1f}",
                r.blocked_successors,
            ])
    print(f"Saved trace CSV: {csv_path} ({len(res.expansion_trace)} expansions)")

    # 2. Write LaTeX fragment
    tex_path = os.path.join(reports_dir, "trace_table.tex")
    
    # Generate human-readable notes from trace values
    rows_tex = []
    for r in res.expansion_trace:
        x, y, t = r.state
        if r.step == 1:
            notes = "Start state popped from open list"
        elif r.blocked_successors > 0:
            notes = f"Adjacent to crossing; successor $(3, 3, 3)$ blocked by AC-1 reservation ({r.blocked_successors} pruned)"
        elif r.step == 4:
            notes = "In-air holding maneuver (wait state at $h=5.0$, $f=8.0$)"
        elif (x, y) == (3, 3):
            notes = "Advances to crossing cell $(3, 3)$ after AC-1 clears"
        else:
            notes = "Unconstrained move towards destination"
        
        row_str = (
            f"{r.step} & $({x}, {y}, t={t})$ & {r.g:.1f} & {r.h:.1f} & {r.f:.1f} & "
            f"{r.blocked_successors} & {notes} \\\\"
        )
        rows_tex.append(row_str)

    tex_content = f"""% Auto-generated by generate_trace.py — DO NOT EDIT MANUALLY
\\begin{{table}}[htbp]
\\centering
\\caption{{Real Measured Expansion Trace for AC-2 in Crossing Routes Scenario (A*). Notes column is descriptive text added for Scenario 2.}}
\\label{{tab:trace_ac2}}
\\resizebox{{\\textwidth}}{{!}}{{%
\\begin{{tabular}}{{ccccccc}}
\\toprule
\\textbf{{Step}} & \\textbf{{State $(x, y, t)$}} & \\textbf{{$g(n)$}} & \\textbf{{$h(n)$}} & \\textbf{{$f(n)$}} & \\textbf{{Blocked}} & \\textbf{{Search Action / Notes}} \\\\
\\midrule
{chr(10).join(rows_tex)}
\\midrule
\\multicolumn{{7}}{{c}}{{\\textit{{Goal $(3, 7, t=8)$ reached at $f=8.0$; popped and validated without further expansion (Total expansions: {res.nodes_expanded})}}}} \\\\
\\bottomrule
\\end{{tabular}}%
}}
\\end{{table}}
"""
    with open(tex_path, "w", encoding="utf-8") as f:
        f.write(tex_content)
    print(f"Saved trace LaTeX fragment: {tex_path}")


if __name__ == "__main__":
    generate_trace()
